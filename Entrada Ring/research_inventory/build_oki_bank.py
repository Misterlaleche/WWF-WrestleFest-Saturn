#!/usr/bin/env python3
"""Build resident original OKI samples with their fixed entrance gains.

The original 12-bit decoder output comes from research_events/export. Only
constant original volume and the MAME 0.264 board-routing gain are applied.
This is a per-instrument/sample bank, never a mixed scene recording.
"""
import argparse
import hashlib
import json
from pathlib import Path
import struct

BASE=0x44000
RATE=8000
PITCH=0x69CE
VOLUMES={1:(3,11),18:(2,16)}
PRIMARY_URL="https://raw.githubusercontent.com/mamedev/mame/mame0264/src/mame/technos/ddragon3.cpp"
PRIMARY_SHA="3c766308ee511828e6d3f2e264e04d769aea98f87e849dd014e8122f69d6633f"

def nearest_even(n,d):
    sign=-1 if n<0 else 1
    q,r=divmod(abs(n),d)
    if 2*r>d or (2*r==d and q&1):q+=1
    return sign*q

def main():
    ap=argparse.ArgumentParser()
    ap.add_argument('--source-dir',type=Path,required=True)
    ap.add_argument('--out',type=Path,required=True)
    args=ap.parse_args()
    args.out.mkdir(parents=True,exist_ok=True)
    bank=bytearray();assets=[]
    for sid,(vol,num) in VOLUMES.items():
        name=f'oki_bank0_sample{sid:03d}.pcm16be'
        original=(args.source_dir/name).read_bytes()
        pcm=struct.unpack('>'+str(len(original)//2)+'h',original)
        # Original OKI volume num/32, board route9/10. No normalization.
        scaled=[nearest_even(x*num*9,320) for x in pcm]
        assert all(-32768<=x<=32767 for x in scaled)
        assert all(abs(x*num*9-y*320)<=160 for x,y in zip(pcm,scaled))
        offset=len(bank)
        data=struct.pack('>'+str(len(scaled))+'h',*scaled)
        bank.extend(data)
        bank.extend(b'\0\0') # Interpolation guard for one-shot LEA=count.
        bank.extend(b'\0'*((-len(bank))%32))
        assets.append(dict(bank=0,sample_id=sid,baked_volume=vol,
                           original_volume_numerator=num,original_volume_denominator=32,
                           reference_route_numerator=9,reference_route_denominator=10,
                           source_pcm_sha256=hashlib.sha256(original).hexdigest(),
                           scaled_pcm_sha256=hashlib.sha256(data).hexdigest(),
                           scsp_address=BASE+offset,bank_offset=offset,
                           samples=len(pcm),pcm_bytes=len(data),guard_samples=1,
                           quantization='round to nearest, ties even; maximum0.5PCM16LSB',
                           peak=max(abs(x) for x in scaled)))
    assert BASE+len(bank)<=0x80000
    (args.out/'oki_volume_bank.bin').write_bytes(bank)
    info=dict(scsp_base=BASE,bytes=len(bank),sha256=hashlib.sha256(bank).hexdigest(),
              source_rate=RATE,scsp_pitch_word=PITCH,
              scsp_effective_rate=44100/8*(1+462/1024),
              pitch_relative_error_ppm=(44100/8*(1+462/1024)/RATE-1)*1e6,
              gain_reference=dict(url=PRIMARY_URL,sha256=PRIMARY_SHA,
                                  lines='925–928',ym_left=0.45,ym_right=0.45,oki=0.90,
                                  note='MAME board-route calibration, not a ROM value. A53 pack0.33/0.66 contradicted this pinned source.'),
              mixed_scene_pcm=False,assets=assets)
    (args.out/'oki_volume_bank.json').write_text(json.dumps(info,indent=2)+'\n')
    h=['/* Generated by build_oki_bank.py from original per-sample PCM. */',
       '#ifndef WP01_OKI_ASSETS_H','#define WP01_OKI_ASSETS_H',
       '#include "wp01_oki.h"',
       f'#define WP01_OKI_BANK_ADDRESS 0x{BASE:X}u',
       f'#define WP01_OKI_BANK_BYTES {len(bank)}u',
       'static const wp01_oki_asset_t wp01_oki_assets[]={']
    h += [f' {{0x{a["scsp_address"]:X}u,{a["samples"]}u,0u,{a["sample_id"]}u,{a["baked_volume"]}u}},' for a in assets]
    h += ['};','#define WP01_OKI_ASSET_COUNT (sizeof(wp01_oki_assets)/sizeof(wp01_oki_assets[0]))','#endif','']
    (args.out/'wp01_oki_assets.h').write_text('\n'.join(h))
    print(json.dumps({k:info[k] for k in ['scsp_base','bytes','sha256','scsp_effective_rate','pitch_relative_error_ppm']}))

if __name__=='__main__':main()
