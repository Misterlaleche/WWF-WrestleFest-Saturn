#!/usr/bin/env python3
"""Compare native C state to independently captured input-only MAME RAM.

This detects changed movement speed, wrong phase update order, missing RNG
branch boundaries, wrong pair sorting, and the asymmetric exit-wipe boundary.
RNG choice bits are replayed from capture; RNG entropy is explicitly outside
this trace equivalence test. No position/phase value is generated by the C.
"""
import argparse, csv, json, subprocess
from pathlib import Path

SOURCE = Path(__file__).resolve().parents[1]
HERE = SOURCE / "test-output"
HERE.mkdir(exist_ok=True)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--ram", type=Path, required=True)
    a = ap.parse_args()
    ram = a.ram.read_bytes()
    assert len(ram) >= 1678*16384
    def rec(frame): return ram[(frame-1)*16384:frame*16384]
    def u16(r,o): return int.from_bytes(r[o:o+2],"big")
    def s16(r,o): return int.from_bytes(r[o:o+2],"big",signed=True)
    def u32(r,o): return int.from_bytes(r[o:o+4],"big")
    choices = []
    for actor in (0x5B0,0x6BC):
        bits=[]
        for n in range(48,321,48):
            phase=u16(rec(1300+n),actor+0x24)&255
            assert phase in (0,4)
            bits.append(0 if phase==4 else 1)
        choices.append(bits)
    (HERE/"trace_rng_choices.h").write_text("static const unsigned trace_bits[2][6]={"+
        ",".join("{"+",".join(map(str,x))+"}" for x in choices)+"};\n")
    source = r'''
#include <stdio.h>
#include <assert.h>
#include "wp01_scene.h"
#include "trace_rng_choices.h"
static unsigned calls[2];
static uint32_t trace_rng(void *ctx,unsigned actor,unsigned n) {
    (void)ctx; assert(actor<2); assert(n%48==0); assert(calls[actor]<6);
    return trace_bits[actor][calls[actor]++];
}
static uint32_t always_alt(void *ctx,unsigned actor,unsigned n) {
    (void)ctx;(void)actor;(void)n;return 0;
}
int main(void) {
    wp01_scene_t s;
    wp01_scene_init(&s,0,7,0);
    wp01_scene_set_rng_hook(&s,trace_rng,NULL);
    puts("frame,actor,type,selector,world_x,world_y,z,sx,sy,correction,counter,phase,light_x,light_y,light_selector,light_counter,light_phase,light_visible,wipe");
    unsigned frames=0;
    while(!s.done) {
        assert(s.frame==frames);
        for(unsigned k=0;k<2;k++) {
            const wp01_scene_actor_t *q=&s.actor[k];
            printf("%u,%u,%u,%u,%d,%ld,%d,%d,%d,%d,%u,%u,%d,%d,%u,%u,%u,%u,%d\n",
                s.frame,k,q->type,q->selector,q->world_x,(long)q->world_y,q->base_z,
                q->sx,q->sy,q->correction_y,q->counter,q->phase,s.light.x,s.light.y,
                s.light.selector,s.light.counter,s.light.phase,s.light.visible,s.wipe_tile);
        }
        wp01_scene_step(&s);frames++;
        assert(frames<=402);
    }
    assert(frames==402);assert(calls[0]==6&&calls[1]==6);
    assert(s.frame==401);assert(s.actor[0].internal_id==7);assert(s.actor[1].internal_id==0);
    wp01_scene_init(&s,0,9,0);assert(s.actor[0].internal_id==9&&s.actor[1].internal_id==0);
    wp01_scene_init(&s,11,10,0);assert(s.actor[0].internal_id==11&&s.actor[1].internal_id==10);
    for(unsigned i=0;i<24;i++)wp01_scene_step(&s);
    assert(s.actor[0].type==0x4A&&s.actor[1].type==0x4A);
    wp01_scene_init(&s,1,2,1);wp01_scene_set_rng_hook(&s,always_alt,NULL);
    for(unsigned i=0;i<72;i++)wp01_scene_step(&s);
    assert(s.actor[0].selector==4&&s.actor[0].correction_y==48);
    assert(s.actor[0].anchor_y==161);assert(s.actor[1].correction_y==0);
    uint32_t rng=0x12345678;
    assert(wp01_rng_21b4(&rng,1,2)==0x62468acfU);
    return 0;
}
'''
    (HERE/"test_native_scene.c").write_text(source)
    exe=HERE/"test_native_scene"
    subprocess.run(["cc","-std=c99","-O2","-Wall","-Wextra","-Werror","-I",str(SOURCE),str(HERE/"test_native_scene.c"),str(SOURCE/"wp01_scene.c"),"-o",str(exe)],check=True)
    run=subprocess.run([str(exe)],capture_output=True,text=True)
    assert run.returncode==0,run.stderr
    (HERE/"native_trace.csv").write_text(run.stdout)
    rows=list(csv.DictReader(run.stdout.splitlines()))
    errors=[]; checked=0
    for row in rows:
        core=int(row["frame"]);k=int(row["actor"])
        if core<24: continue
        original=rec(1277+core); actor=(0x5B0,0x6BC)[k]; light=0x14CE
        expected={"type":u16(original,actor+2),"selector":u16(original,actor+4),
                  "world_x":s16(original,actor+6),"world_y":u32(original,actor+10),
                  "z":s16(original,actor+14),"sx":s16(original,actor+20),"sy":s16(original,actor+22),
                  "correction":int.from_bytes(original[actor+27:actor+28],"big",signed=True),
                  "counter":u16(original,actor+34),"phase":u16(original,actor+36),
                  "light_x":s16(original,light+20),"light_y":232-s16(original,light+22),
                  "light_selector":u16(original,light+4),"light_counter":u16(original,light+34),
                  "light_phase":u16(original,light+36),
                  "light_visible":int(u16(original,light+4)!=65535)}
        for field,value in expected.items():
            if int(row[field])!=value: errors.append({"core_frame":core,"mame_frame":1277+core,"actor":k,"field":field,"expected":value,"actual":int(row[field])})
        checked+=1
    assert not errors,json.dumps(errors[:20],indent=2)
    summary={"pass":True,"mame_actor_states_compared":checked,"source_ram":str(a.ram),
             "core_frames":402,"replayed_rng_bits":choices,"evidence":"Input-only MAME0.264 full RAM capture; no CPU register or RAM injection"}
    (HERE/"native_scene_test_results.json").write_text(json.dumps(summary,indent=2)+"\n")
    print(json.dumps(summary))


if __name__=="__main__":main()
