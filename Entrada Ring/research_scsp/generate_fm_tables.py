"""Derive SCSP bridge constants from primary YMFM/Mednafen models.

This generates oscillator data, never a rendered note, channel, or song.
The original OPM logarithmic sine shape comes from ymfm's published tables.
"""
from pathlib import Path
import hashlib
import json
import math
import re
import struct

HERE = Path(__file__).resolve().parent
text = (HERE / "ymfm_fm.ipp").read_text()

def body(name):
    s = text.index(name)
    start = text.index("{", s)
    end = text.index("};", start)
    return re.sub(r"//[^\n]*", "", text[start + 1:end])

phase = [int(n) for n in re.findall(r"\b\d+\b", body("s_phase_step["))]
detune = [int(n) for n in re.findall(r"\b\d+\b", body("s_detune_adjustment["))]
sine_log = [int(n, 16) for n in re.findall(r"0x[0-9a-fA-F]+", body("s_sin_table["))]
power = [((int(n, 16) | 0x400) << 2) for n in re.findall(r"X\((0x[0-9a-fA-F]+)\)", body("s_power_table["))]
increments = [int(n, 16) for n in re.findall(r"0x[0-9a-fA-F]+", body("s_increment_table["))]
assert [len(x) for x in (phase, detune, sine_log, power, increments)] == [768, 128, 256, 256, 64]

# Original OPM waveform, expanded fourfold to exploit signed16 sample precision.
wave = []
for i in range(1024):
    index = (~i if i & 0x100 else i) & 255
    a = sine_log[index]
    v = power[a & 255] >> (a >> 8)
    wave.append((-v if i & 0x200 else v) * 4)
assert max(map(abs, wave)) <= 32767
# SA=0x10000, documented maximum modulation displacement +/-32768 samples.
# Include a full additional cycle plus the interpolation guard after the centre.
guarded = [wave[i & 1023] for i in range(66560)]
# Terminal carriers use a separate bank with the original board's mono mix gain.
# This preserves modulation index because no carrier in this cue feeds another op.
guarded += [round(wave[i & 1023] * 0.90) for i in range(66560)]
pcm = struct.pack(">" + "h" * len(guarded), *guarded)
(HERE / "FM-SINE.PCM").write_bytes(pcm)

# Evaluate average envelope increments of the documented bit-clock algorithms.
# YM effective rates are 6-bit, SCSP effective rates are 5-bit. Map by closest
# mean logarithmic attenuation slope at the original chip and native SCSP rates.
opm_slope = []
for r in range(64):
    p = increments[r]
    mean = sum((p >> (4 * n)) & 15 for n in range(8)) / 8
    period = max(1, 1 << max(0, 11 - (r >> 2)))
    opm_slope.append(mean / period * (3579545 / 64 / 3))

scsp_slope = []
for r in range(32):
    inc_sum = 0
    count = 32768
    for sc in range(count):
        scxc = (sc ^ (sc - 1)) & (sc ^ 1)
        wbt = (24 - min(24, r)) >> 1
        adj = (r < 24) and (r & 1)
        clock = ((scxc | (scxc >> adj)) >> (wbt + adj)) & bool(r)
        if clock:
            er = max(24, min(30, r))
            shift = ((32 - er) >> 1) + (er & 1 & (sc >> (wbt + 1)))
            inc_sum += 16 >> shift
    scsp_slope.append(inc_sum / count * 44100)

def closest(v):
    if not v:
        return 0
    return min(range(1, 31), key=lambda r: abs(math.log(scsp_slope[r] / v)))

rates = [closest(v) for v in opm_slope]
attack = rates.copy()  # both chips use (-attenuation-1) times decay_step/16.
attack[62] = attack[63] = 31  # EGHOLD produces the initial full-level step.

def arr(name, values, ctype="uint32_t", width=16):
    lines = [f"static const {ctype} {name}[{len(values)}] = {{"]
    for off in range(0, len(values), width):
        lines.append("    " + ",".join(map(str, values[off:off+width])) + ",")
    return "\n".join(lines + ["};", ""])

header = "/* Generated by generate_fm_tables.py; YMFM data: BSD-3-Clause, Aaron Giles. */\n"
header += arr("fm_phase_step", phase)
header += arr("fm_detune", detune, "uint8_t")
header += arr("fm_rate", rates, "uint8_t")
header += arr("fm_attack_rate", attack, "uint8_t")
(HERE / "wp01_fm_tables.h").write_text(header)
manifest = {
    "oscillator": "YMFM OPM log-sine/power tables, one 1024-sample cycle, fourfold linear scale",
    "contains_notes_or_song_recording": False,
    "ram_base": 0,
    "start_address": 65536,
    "carrier_start_address": 0x30800,
    "carrier_board_gain": 0.90,
    "loop_start": 0,
    "loop_end": 1024,
    "bytes": len(pcm),
    "sha256": hashlib.sha256(pcm).hexdigest(),
    "ym_clock_hz": 3579545,
    "scsp_rate_hz": 44100,
    "sources": {n: hashlib.sha256((HERE / n).read_bytes()).hexdigest() for n in ["ymfm_fm.ipp", "ymfm_opm.cpp", "scsp_mdfn.inc", "SCSP-MANUAL.pdf"]},
    "opm_envelope_attenuation_per_second": opm_slope,
    "scsp_envelope_attenuation_per_second": scsp_slope,
    "rate_map": rates,
    "attack_map": attack,
    "limitations": [
        "SCSP EG starts at attenuation 0x280; OPM retains/retriggers from its own envelope state.",
        "SCSP has 32 rate levels, OPM 64. Mapping minimizes mean-slope error, not samplewise envelope error.",
        "SCSP EG amplitude interpolation differs from OPM logarithmic exponent lookup.",
        "Instant OPM attack uses SCSP EGHOLD with maximum attack; decay begins after the native attack phase.",
        "SCSP synthesis pipeline and 44.1kHz sample clock differ from OPM.",
    ],
}
(HERE / "fm-mapping-manifest.json").write_text(json.dumps(manifest, indent=2) + "\n")
(HERE / "YMFM-LICENSE.txt").write_text("\n".join(line[3:] if line.startswith("// ") else "" for line in text.splitlines()[:29]) + "\n")
print(json.dumps({"sine_bytes":len(pcm),"phase_table":len(phase),"rate_map":rates,"sha256":manifest["sha256"]}))
