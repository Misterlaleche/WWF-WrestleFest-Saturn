"""Assemble the native four-PCM SCSP DSP program, using zero FM slots."""
import argparse,json
from pathlib import Path
FIELDS={
 'tra':(0,8,7),'twt':(0,7,1),'twa':(0,0,7),
 'xsel':(1,15,1),'ysel':(1,13,2),'ira':(1,6,6),'iwt':(1,5,1),'iwa':(1,0,5),
 'table':(2,15,1),'mwt':(2,14,1),'mrd':(2,13,1),'ewt':(2,12,1),'ewa':(2,8,4),
 'adrl':(2,7,1),'frcl':(2,6,1),'shift':(2,4,2),'yrl':(2,3,1),'negb':(2,2,1),'zero':(2,1,1),'bsel':(2,0,1),
 # SCSP NOFL is bit8 of word3; bit15 is reserved (older MAME used bit15).
 'nofl':(3,8,1),'coef':(3,9,6),'masa':(3,2,5),'adreb':(3,1,1),'nxadr':(3,0,1)}
def instruction(**args):
    # A true pipeline NOP: preserve ACC without touching state or RAM.
    fields=dict(xsel=1,ysel=1,ira=0,coef=63,bsel=1,shift=3)
    fields.update(args);words=[0]*4
    for k,v in fields.items():
        word,shift,bits=FIELDS[k]
        if not 0<=v<1<<bits:raise ValueError(k)
        words[word]|=v<<shift
    return words
def build_program():
    p=[]
    def emit(**kw):p.append(instruction(**kw))
    emit();emit(table=1,mrd=1,masa=0);emit();emit()
    emit(iwt=1,iwa=0)
    emit(table=1,mrd=1,masa=1);emit();emit();emit(iwt=1,iwa=1)
    # Packed -8388608 in MADRS7 centers unsigned4096 phases in signed ADRS.
    emit(table=1,mrd=1,masa=7);emit();emit();emit(iwt=1,iwa=10)
    # Counter Q8, stable1 while gated, then +1 each SCSP frame. TEMP rotates
    # by DEC, so previous frame's TWA0 is addressed by TRA1 this frame.
    emit(xsel=0,tra=1,coef=9,zero=1,bsel=0)
    emit(xsel=1,ira=0,coef=0,negb=1)
    emit(twt=1,twa=0,table=1,mwt=1,masa=2,nofl=1)
    for v in range(4):
        phase=8+v*16;term0=phase+2;term1=phase+3;interp=phase+4
        a,b=2+v*2,3+v*2
        emit(xsel=0,tra=phase+1,coef=1+v,zero=1,bsel=0)
        emit(xsel=1,ira=1,coef=0,negb=1)
        # Preserve the unmodified phase and fractional latch. ADRS is signed12:
        # wrap24(phase-0x800000) addresses -2048..2047 from a centered MADRS.
        # COEF0 is -unity; two negations add MEMS10 without a +unity constant.
        emit(twt=1,twa=phase,frcl=1,xsel=1,ira=10,coef=0,negb=1)
        emit(negb=1)
        emit(adrl=1)
        emit(table=1,mrd=1,masa=3+v,adreb=1,nofl=1)
        emit();emit();emit(iwt=1,iwa=a)
        emit(table=1,mrd=1,masa=3+v,adreb=1,nxadr=1,nofl=1)
        emit();emit();emit(iwt=1,iwa=b)
        # Weighted sum avoids overflowing a signed24 sample difference.
        emit(xsel=1,ira=a,ysel=0,zero=1,bsel=0)
        emit(twt=1,twa=term0,xsel=1,ira=b,ysel=0,zero=1,bsel=0)
        emit(twt=1,twa=term1,xsel=1,ira=a,coef=0,zero=1,bsel=0)
        emit(xsel=0,tra=term0,coef=0,negb=1)
        emit(xsel=0,tra=term1,coef=0,negb=1)
        emit(twt=1,twa=interp,shift=0)
        emit(xsel=0,tra=interp,coef=5+v,zero=1,bsel=0)
        emit(ewt=1,ewa=v,shift=0);emit()
    for ch in range(8):
        emit(xsel=1,ira=0x28+ch,coef=10,zero=1,bsel=0)
        emit(ewt=1,ewa=4+ch,shift=0)
    assert len(p)==120
    # Twelve RAM operations per frame: three constants, clock write, 2*4 PCM.
    assert sum(bool(w[2]&0x6000) for w in p)==12
    assert all(i&1 for i,w in enumerate(p) if w[2]&0x6000)
    return p+[[0]*4 for _ in range(128-len(p))]
def generate(out):
    out.mkdir(parents=True,exist_ok=True);p=build_program()
    h=['/* Generated by build_dsp_mixer.py; 120 active steps, 12 RAM accesses. */',
       'static const uint16_t wf_dsp_program[128][4]={']
    h+=[' {'+','.join('0x%04x'%x for x in w)+'},' for w in p]
    (out/'wf_dsp_program.h').write_text('\n'.join(h+['};'])+'\n')
    (out/'dsp-program.json').write_text(json.dumps(dict(steps=120,ram_accesses=12,fm_slots_used=0,program=p),indent=2)+'\n')
if __name__=='__main__':
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--out',type=Path,required=True);generate(p.parse_args().out)
