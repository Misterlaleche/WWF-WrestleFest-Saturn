#!/usr/bin/env python3
"""Rebuild/replay the archived same-TAG native SH2 event checkpoint.

Use --fixture with the manifest freshly generated by
build_sh2_checkpoint_fixture.py from this package, the supplied ROM, SDK and
WP1979 source. The old explicit private-directory interface remains available
for archived evidence. Builds both variants into a new private output. Capture
is explicit (--run), read-only, native Mednafen1.32.1, normal presentation speed,
no cartridge or game changes.
"""
from pathlib import Path
import argparse
import hashlib
import importlib.util
import json
import os
import re
import shutil
import subprocess
import sys

EXPECTED_COUNT = 65536
EXPECTED_HASH = 0x4D3EF2A3
EXPECTED_CYCLE = 108786762
BASE_NATIVE_SHA = '983bde9378737eeb6bdcf0ed9ff15a5b535ad55ed61ea87a84516b1613b04939'
SELECTED_NATIVE_SHA = 'c408e4a8ad5d7b54a55706f4c96fd9f4d39271dcd0fb5e2de14331af138f4fad'
EXPECTED_MODULE_SHA = {
    'baseline': '2a2ae43dd9be511c746e9cb147e4eb7f464197b80916964d9d945da348e466b9',
    'scalar9-seq-os': 'bc5a5e0314f4e8a3fd39238fad3a7288fb5393c2de327b79bb3ac16b5dce32b0',
}
EXPECTED_FIRMWARE_SHA = 'b5ecee6e3e2a0efe7c13f1c6f4cb89bbc6b18cb96db23a57203b20e4a2b06b66'


def sha(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def module(name, path):
    spec = importlib.util.spec_from_file_location(name, path)
    result = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(result)
    return result


def main():
    p = argparse.ArgumentParser(description=__doc__)
    for name in ('sdk', 'out'):
        p.add_argument('--' + name, type=Path, required=True)
    p.add_argument('--fixture', type=Path, help='Source-generated fixture.json; no archived private tree required')
    p.add_argument('--profiled-base', type=Path, help='Legacy explicit archived fixture interface')
    p.add_argument('--game-build', type=Path, help='Legacy explicit archived game build interface')
    p.add_argument('--production', type=Path, default=Path(__file__).resolve().parents[1])
    p.add_argument('--run', action='store_true')
    p.add_argument('--environment-root', type=Path)
    p.add_argument('--bios', type=Path)
    p.add_argument('--display', type=int, default=96)
    a = p.parse_args()
    fixture_identity = None
    if a.fixture:
        if a.profiled_base or a.game_build:
            p.error('Use --fixture or both explicit legacy directories, not both')
        fixture_identity = json.loads(a.fixture.read_text())
        if (fixture_identity.get('kind') != 'wf_sh2_checkpoint_fixture_v1' or
                fixture_identity.get('passed') is not True or
                fixture_identity.get('build_directory') != 'build' or
                fixture_identity.get('native_emulator_started') is not False):
            p.error('Require a completed, source-generated checkpoint fixture')
        a.profiled_base = a.fixture.resolve().parent / 'build'
        a.game_build = a.profiled_base
    elif not a.profiled_base or not a.game_build:
        p.error('Use --fixture or supply both --profiled-base and --game-build')
    root, base, game, sdk, out = (getattr(a, n).resolve() for n in
                                 ('production', 'profiled_base', 'game_build', 'sdk', 'out'))
    protected = {root, base, game, sdk}
    for parent in root.parents:
        if (parent / '.git').exists():
            protected.add(parent)
            break
    if a.out.is_symlink() or out.exists() or any(out == x or x in out.parents for x in protected):
        p.error('Use a fresh private output outside production')
    if a.run and (not a.environment_root or not a.bios):
        p.error('--run requires --environment-root and --bios')
    if sha(base / 'audio2/src/reference_driver/z80-native.c') != BASE_NATIVE_SHA:
        raise ValueError('Require the preserved pre-scalar9 profiled base')
    if sha(root / 'src/reference_driver/z80-native.c') != SELECTED_NATIVE_SHA:
        raise ValueError('This historical replay requires the measured scalar9 source')
    if sha(game / 'profiles/audio2/cd/SCSP.ELF') != EXPECTED_FIRMWARE_SHA:
        raise ValueError('Require the exact archived firmware10; another firmware is a different experiment')
    if fixture_identity and sha(game / 'profiles/audio2/AUDIO2TAG.bin') != fixture_identity['master_bin_sha256']:
        raise ValueError('Generated game binary differs from its fixture identity')
    observer = (base / 'audio2/src/wf_music_module.c').read_text()
    if 'wf_sh2_cost_profile[32]' not in observer or '65536u' not in observer:
        raise ValueError('Require the archived32-counter native event observer')
    prior = json.loads((base / 'commands.json').read_text())
    original_compile = next(x['command'] for x in prior
                            if '-c' in x['command'] and any(y.endswith('/wf_music_module.c') for y in x['command']))
    old_source = next(x for x in original_compile if x.endswith('/wf_music_module.c')).rsplit('/audio2/', 1)[0]
    old_sdk = str(Path(original_compile[0]).parent.parent)
    compact = module('sh2_compact', root / 'integration/compact_music_elf.py')
    out.mkdir(parents=True)
    report = {'scope': 'Instrumented audio subsystem during unchanged TAG; not final cadence, fidelity or continuity',
              'profiled_base': str(base), 'game_build': str(game),
              'source_generated_fixture': str(a.fixture.resolve()) if a.fixture else None,
              'reference': {'source': 'Untouched R01/original scalar Z80',
                            'count': EXPECTED_COUNT, 'hash32': f'{EXPECTED_HASH:08x}', 'cycle': EXPECTED_CYCLE},
              'native_capture_requested': a.run, 'variants': []}

    def record():
        (out / 'checkpoint.json').write_text(json.dumps(report, indent=2) + '\n')

    for variant in ('baseline', 'scalar9-seq-os'):
        dest = out / variant
        dest.mkdir()
        for folder in ('module', 'audio2'):
            shutil.copytree(base / folder, dest / folder)
        if variant != 'baseline':
            shutil.copyfile(root / 'src/reference_driver/z80-native.c', dest / 'audio2/src/reference_driver/z80-native.c')
        item = {'variant': variant, 'commands': []}
        report['variants'].append(item)

        def run(command, cwd=dest / 'module', env=None):
            command = list(map(str, command))
            r = subprocess.run(command, cwd=cwd, env=env, text=True, capture_output=True)
            item['commands'].append({'command': command, 'cwd': str(cwd),
                                      'returncode': r.returncode, 'stdout': r.stdout, 'stderr': r.stderr})
            record()
            if r.returncode:
                raise RuntimeError(r.stderr or r.stdout)
            return r.stdout

        def relocate(command):
            return [arg.replace(old_source, str(dest)).replace(old_sdk, str(sdk)) for arg in command]

        for name in ('wf_music_module.c', 'wf_music_seq.c', 'z80-native.c'):
            command = next(x['command'] for x in prior if '-c' in x['command'] and any(y.endswith('/' + name) for y in x['command']))
            command = relocate(command)
            if variant != 'baseline' and name == 'wf_music_seq.c':
                command = ['-Os' if arg == '-O2' else arg for arg in command]
            run(command)
        run(relocate(next(x['command'] for x in prior if x['command'][0].endswith('sh2eb-elf-ld'))))
        elf = dest / 'module/MUSIC4.DEBUG.ELF'
        nm = run([sdk / 'bin/sh2eb-elf-nm', '-n', elf])
        symbols = {bits[2]: int(bits[0], 16) for line in nm.splitlines() if len(bits := line.split()) == 3}
        used = symbols['_wf_hotcode_end'] - symbols['_wf_hotcode_start'] + 3220
        if used > 18432:
            raise ValueError('Observer/variant exceeds the unchanged18KiB window')
        packed = compact.compact(elf.read_bytes())
        (dest / 'MUSIC4.ELF').write_bytes(packed)
        if variant == 'baseline' and packed != (base / 'cd/MUSIC4.ELF').read_bytes():
            raise ValueError('Rebuilt baseline payload differs from archived bytes')
        if sha(dest / 'MUSIC4.ELF') != EXPECTED_MODULE_SHA[variant]:
            raise ValueError('Rebuilt variant differs from the actually measured module: ' + variant)
        item.update(module_sha256=sha(dest / 'MUSIC4.ELF'), hot_used_bytes=used,
                    native_source_sha256=sha(dest / 'audio2/src/reference_driver/z80-native.c'))
        (dest / 'module-symbols.json').write_text(json.dumps(symbols, indent=2) + '\n')
        native = dest / 'native'
        native.mkdir()
        shutil.copytree(game / 'profiles/audio2/cd', native / 'cd')
        shutil.copyfile(dest / 'MUSIC4.ELF', native / 'cd/MUSIC4.ELF')
        shutil.copyfile(game / 'profiles/audio2/IP.BIN', native / 'IP.BIN')
        env = dict(os.environ, YAUL_INSTALL_ROOT=str(sdk), YAUL_ARCH_SH_PREFIX='sh2eb-elf', YAUL_PROG_SH_PREFIX='sh2eb-elf')
        run([sdk / 'bin/make-iso', native / 'cd', native / 'IP.BIN', native, 'AUDIO2TAG'], env=env)
        cue = native / 'AUDIO2TAG.cue'
        cue.write_text('FILE "AUDIO2TAG.iso" BINARY\n  TRACK 01 MODE1/2048\n    INDEX 01 00:00:00\n')
        command = json.loads((game / 'capture-profile-command.json').read_text())
        command[0:2] = [sys.executable, str(root / 'tools/capture_mednafen.py')]
        for flag, value in [('--cue', str(cue)), ('--out', str(dest / 'capture')),
                            ('--stop-watch', 'worker_31'), ('--stop-value', '1'),
                            ('--seconds', '120'), ('--display', str(a.display))]:
            command[command.index(flag) + 1] = value
        if a.run:
            for flag, value in [('--environment-root', str(a.environment_root.resolve())), ('--bios', str(a.bios.resolve()))]:
                command[command.index(flag) + 1] = value
        for i, value in enumerate(command):
            if value == '--watch' and re.match(r'^worker_[0-9]+:', command[i + 1]):
                index = int(command[i + 1].split(':')[0].split('_')[1])
                command[i + 1] = f'worker_{index}:{symbols["_wf_sh2_cost_profile"] + index * 4:#x}:4'
        for i in range(17, 32):
            command += ['--watch', f'worker_{i}:{symbols["_wf_sh2_cost_profile"] + i * 4:#x}:4']
        (dest / 'capture-command.json').write_text(json.dumps(command, indent=2) + '\n')
        item['firmware_sha256'] = sha(native / 'cd/SCSP.ELF')
        item['iso_sha256'] = sha(native / 'AUDIO2TAG.iso')
        record()
        if not a.run:
            continue
        with (dest / 'capture.log').open('w') as log:
            result = subprocess.run(command, stdout=log, stderr=subprocess.STDOUT)
        if result.returncode:
            raise RuntimeError('Capture failed; native artifacts preserved')
        capture = json.loads((dest / 'capture/report.json').read_text())
        w = capture['final_watch_values']
        reader = module('sh2_state', root / 'tools/analyze_audio_capture.py')
        metadata, sections = reader.read_state(capture['native_state']['path'])
        order = metadata['data_byte_order']
        divisor = int.from_bytes(sections['SMPC']['CurrentClockDivisor'], order)
        frt = int.from_bytes(sections['SH2-S']['FRT.TCR'], order)
        if divisor != 65 or frt != 2:
            raise ValueError('Native clock differs from the archived benchmark')
        valid = (w['worker_31'] == 1 and w['worker_17'] == EXPECTED_COUNT and
                 w['worker_18'] == EXPECTED_HASH and w['worker_19'] == EXPECTED_CYCLE and
                 not w['api_error'] and not w['worker_error'])
        virtual = (w['worker_27'] - 2 * 3579545) / 3579545
        seconds = w['worker_20'] / (1746818182 / divisor / 128)
        item['native'] = {'checkpoint_agrees': valid, 'counts': w,
                          'emulator_sha256': capture['emulator_sha256'],
                          'sequence_seconds': seconds, 'virtual_seconds': virtual,
                          'inclusive_sequence_seconds_per_virtual_second': seconds / virtual,
                          'note': 'Digest/count/final cycle agree; this does not measure PCM fidelity or final gameplay cadence.'}
        record()
        if not valid:
            raise RuntimeError('Native checkpoint failed; no acceptance claimed')
    print(json.dumps({'report': str(out / 'checkpoint.json'), 'native_capture_requested': a.run}))
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
