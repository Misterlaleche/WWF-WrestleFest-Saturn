#include "wf_collision.h"
static const uint8_t norm24[0x24]={
 0x0B,0x0C,0x0B,0x0C,0x0D,0x05,0x06,0x07,0x08,0x09,0x0A,0x0B,
 0x0C,0x0D,0x0E,0x0F,0x0B,0x0B,0x0B,0x0B,0x0B,0x0B,0x0B,0x0B,
 0x0B,0x0B,0x0B,0x0B,0x0B,0x0B,0x0B,0x0B,0x0B,0x0B,0x0C,0x0D
};
uint8_t wf_collision_normalize_low(uint8_t s){ return s<0x24u?norm24[s]:s; }
void wf_collision_normalize_receiver(wf_actor_raw_t *src,wf_actor_raw_t *dst){
 uint8_t s=wf_state4_subtype(dst); if(s>=0x24u)return;
 if((wf_u8(src,WF_A_FACING)&0x80u)!=(wf_u8(dst,WF_A_FACING)&0x80u))return;
 wf_state4_write_low(dst,wf_collision_normalize_low(s));
}
