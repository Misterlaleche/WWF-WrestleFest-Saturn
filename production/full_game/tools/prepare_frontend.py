#!/usr/bin/env python3
"""Derive only rendering from hash-locked TEST03; no private main/input/clock."""
import hashlib,json,re,zlib
from pathlib import Path
root=Path(__file__).resolve().parents[1]
src=root/'vendor/frontend_test03/main.c'
raw=src.read_bytes()
assert hashlib.sha256(raw).hexdigest()=='65797db05530edefabef811d88887bd9bd75412cc8111451c9d8cd35f2fafb00'
s=raw.decode()
# Every source slice is identified in the resulting provenance report.
pieces=[s[:s.index('static smpc_peripheral_digital_t pad;')],
'''static struct { uint8_t background[MODE_BITMAP_BYTES]; uint8_t world[SRC_WORLD_BYTES]; } scratch __attribute__((aligned(4)));
#define mode_bitmap scratch.background
#define select_bg_bitmap scratch.background
#define select_world scratch.world
static uint16_t base_palette[256] __attribute__((aligned(4)));
static uint8_t patch96[96U*96U] __attribute__((aligned(4)));
''',
s[s.index('static void dma_copy'):s.index('static void arcade_logic_wait')],
s[s.index('/* ROM $005518'):s.index('static unsigned direction_code')],
s[s.index('static void vram_clear32'):s.index('void user_init(void)')],
s[s.index('void user_init(void)'):s.index('int main(void)')]]
out=''.join(pieces).replace('#include "nav_tables.h"','#include "wf_frontend_video.h"\n#include "wf_frontend_resources.h"')
asset_names=[('asset_modex','MODEX.RLE'),('asset_modepal','MODE.PAL'),('asset_cursor0','CURSOR0.BIN'),('asset_cursor0pal','CURSOR0.PAL'),('asset_selbg','SELBG.RLE'),('asset_selworld','SELWORLD.RLE'),('asset_selpal','SELPAL.BIN')]
for i,(symbol,name) in enumerate(asset_names):
 out=out.replace('extern uint8_t '+symbol+'[];','#define '+symbol+' ((uint8_t*)wf_frontend_resources['+str(i)+'])')
out=out.replace('static void roster_init(void)','bool wf_frontend_video_roster(void)')
out=out.replace('void user_init(void)','bool wf_frontend_video_mode(void)')
out=out.replace(' smpc_peripheral_init();vdp_sync_vblank_out_set(intback,NULL);','')
out=out.replace('while(true)sync_n(1);','return false;')
# Both load routines finish identically; signal explicit loading completion.
needle='vdp2_tvmd_display_set();\n}'
assert out.count(needle)==2
out=out.replace(needle,'vdp2_tvmd_display_set();\n return true;\n}')
out+='''void wf_frontend_video_apply(const wf_frontend_t *f,const wf_frontend_effect_t *e){
 if(e->palette)mode_set_family_palette(e->family,e->phase);
 if(e->cursor){cursor_patch_upload(e->old_slot,false);cursor_patch_upload(f->slot,true);}
 if(e->scroll)set_fg_scroll(f->scroll);
 if(e->confirm)confirmed_rebuild(f->page,f->slot);
}
'''
build=root/'build/frontend';build.mkdir(parents=True,exist_ok=True)
(build/'renderer.c').write_text('/* Generated by tools/prepare_frontend.py from approved TEST03. */\n'+out)
(build/'provenance.json').write_text(json.dumps({'source':str(src.relative_to(root)),'source_sha256':hashlib.sha256(raw).hexdigest(),'changes':['remove main, SMPC polling, private clock and navigation','export render/load functions; return failure instead of infinite loading','reuse mode bitmap storage for roster background: save122880 B','apply step effects with original render functions'],'renderer_sha256':hashlib.sha256((build/'renderer.c').read_bytes()).hexdigest()},indent=2)+'\n')

records={Path(r['path']).name:r for r in json.loads((root/'vendor/frontend_test03/SOURCE.json').read_text())['files'] if r['path'].startswith('REFERENCE-SOURCE/assets/')}
manifest=[]
for symbol,name in asset_names:
 data=(root/'build/cd'/name).read_bytes();r=records[name]
 if len(data)!=r['bytes'] or hashlib.sha256(data).hexdigest()!=r['sha256']:raise SystemExit('Wrong resource: '+name)
 manifest.append(' {"'+name+'",'+str(len(data))+'u,0x'+format(zlib.crc32(data),'08x')+'u}')
(build/'asset_manifest.h').write_text('/* Verified TEST03 resources, CRC32 for disc integrity. */\n#include "wf_assets.h"\nstatic const wf_asset_t frontend_manifest[]={\n'+',\n'.join(manifest)+'\n};\n')

royal=root.parent.parent/'modo Royal/wp1980/work/hwfix01/native'
for sub in ('src/wf_r18_cdfs.c','src/wp1979_cd_read.c','include/wf_r18_cdfs.h','include/wp1979_cd_read.h'):
 (build/Path(sub).name).write_bytes((royal/sub).read_bytes())
