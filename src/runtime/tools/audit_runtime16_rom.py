assert [struct.unpack_from('>H',b,0xfdb4+i*2)[0] for i in range(12)]==[0x930,0x846,0xb7e,0xa1c,0xb08,0x8bc,0xa90,0xa1c,0x9a6,0xb08,0x930,0xb08]
