typedef struct {const uint8_t *p,*end;uint32_t bits;unsigned count;} reader_t;
static inline int take(reader_t *r,unsigned n,unsigned *out){
    while(r->count<n){
        if(r->p==r->end)return -1;
        r->bits|=(uint32_t)*r->p++<<r->count;r->count+=8u;
    }
    *out=(unsigned)(r->bits&((1u<<n)-1u));
    r->bits>>=n;r->count-=n;return 0;
}
int wp1980_inflate_fixed(const uint8_t *source,size_t source_bytes,
                         uint8_t *output,size_t output_bytes){
    if(!source||!output||!source_bytes)return -1;
    reader_t r={source,source+source_bytes,0,0};
    uint8_t *out=output,*end=output+output_bytes;
    unsigned final=0;
    do{
        unsigned type;
        if(take(&r,1,&final)||take(&r,2,&type))return -1;
        if(type==0u){
            unsigned skip=r.count&7u,ignored,n,inverse;
            if(take(&r,skip,&ignored)||take(&r,16,&n)||take(&r,16,&inverse))return -1;
            if((n^inverse)!=65535u||(size_t)(end-out)<n)return -1;
            while(n--){unsigned byte;if(take(&r,8,&byte))return -1;*out++=(uint8_t)byte;}
        }else if(type==1u){
            for(;;){
                while(r.count<9u&&r.p!=r.end){r.bits|=(uint32_t)*r.p++<<r.count;r.count+=8u;}
                unsigned entry=fixed_lut[r.bits&511u],n=entry>>9,symbol=entry&511u;
                if(r.count<n)return -1;
                r.bits>>=n;r.count-=n;
                if(symbol<256u){if(out==end)return -1;*out++=(uint8_t)symbol;continue;}
                if(symbol==256u)break;
                if(symbol>285u)return -1;
                unsigned extra,length,index=symbol-257u;
                if(take(&r,length_extra[index],&extra))return -1;
                length=length_base[index]+extra;
                if(take(&r,5,&index))return -1;
                index=reverse5[index];if(index>=30u)return -1;
                unsigned dbits=index<4u?0u:(index>>1)-1u;
                if(take(&r,dbits,&extra))return -1;
                unsigned distance=distance_base[index]+extra;
                if(distance>(size_t)(out-output)||length>(size_t)(end-out))return -1;
                const uint8_t *copy=out-distance;
                /* Four-byte copies are legal only for nonoverlapping aligned
                 * words. __builtin_memcpy preserves C effective-type rules. */
                if(distance>=4u&&(((uintptr_t)out|(uintptr_t)copy)&3u)==0u){
                    while(length>=4u){
                        __builtin_memcpy(__builtin_assume_aligned(out,4),
                                         __builtin_assume_aligned(copy,4),4);
                        out+=4;copy+=4;length-=4;
                    }
                }
                while(length--)*out++=*copy++;
            }
        }else return -1;
    }while(!final);
    return out==end&&r.p==r.end&&r.count<8u?0:-1;
}
