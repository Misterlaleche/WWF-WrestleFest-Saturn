#!/usr/bin/env python3
"""Generate or verify the exact 18 canonical WAV headers used at cold boot.

Run --verify before any build/package that uses the generated table. Full-file
hashes detect same-size substitutions; runtime validates ISO size and format.
This command never changes WAV files.
"""
import argparse, hashlib, json, re, struct
from pathlib import Path

NAMES=tuple(f'MU{i:02X}.WAV' for i in range(1,19))

def inspect(name, data):
    if len(data)<46 or len(data)>0x7fffffff:raise ValueError(f'{name}: file size')
    riff,size,wave,fmt,fmt_size,encoding,channels,rate,byte_rate,align,bits,chunk,length=struct.unpack('<4sI4s4sIHHIIHH4sI',data[:44])
    if (riff,wave,fmt,chunk)!=(b'RIFF',b'WAVE',b'fmt ',b'data'):raise ValueError(f'{name}: canonical chunks required')
    if size!=len(data)-8 or length!=len(data)-44:raise ValueError(f'{name}: RIFF/data length')
    if fmt_size!=16 or encoding!=1 or bits!=16 or channels not in (1,2):raise ValueError(f'{name}: canonical PCM16 required')
    if not 0<rate<=88200 or align!=channels*2 or byte_rate!=rate*align or length%align:raise ValueError(f'{name}: PCM dimensions')
    return {'name':name,'size':len(data),'sha256':hashlib.sha256(data).hexdigest(),'header_hex':data[:44].hex()}

def collect(cd):
    unexpected=sorted(p.name for p in cd.iterdir() if re.fullmatch(r'MU[0-9A-F]{2}\.WAV',p.name) and p.name not in NAMES)
    if unexpected:raise ValueError(f'unexpected music cues: {unexpected}')
    return [inspect(name,(cd/name).read_bytes()) for name in NAMES]

def render(rows):
    s='/* Generated by tools/generate_music_headers.py; verify against full WAV hashes before build. */\n'
    s+='#ifndef WF_JO_MUSIC_HEADERS_H\n#define WF_JO_MUSIC_HEADERS_H\n#include <stdint.h>\n'
    s+='typedef struct { uint8_t header[44]; uint32_t file_size; } wf_jo_music_header_t;\n'
    s+='_Static_assert(sizeof(wf_jo_music_header_t)==48, "WAV header table entry size");\n'
    s+='static const wf_jo_music_header_t wf_jo_music_headers[18] = {\n'
    for row in rows:
        s+='    { {'+','.join('0x'+row['header_hex'][i:i+2] for i in range(0,88,2))+'}, '+str(row['size'])+'u }, /* '+row['name']+' */\n'
    return s+'};\n#endif\n'

def provenance(rows):
    return {'format':'WF_MUSIC_HEADERS_V1','runtime_table_bytes':864,'cue_order':list(NAMES),'files':rows}

def generate(cd,header,manifest):
    rows=collect(cd)
    header.parent.mkdir(parents=True,exist_ok=True);manifest.parent.mkdir(parents=True,exist_ok=True)
    header.write_text(render(rows));manifest.write_text(json.dumps(provenance(rows),indent=2)+'\n')
    return rows

def verify(cd,header,manifest):
    rows=collect(cd)
    if json.loads(manifest.read_text())!=provenance(rows):raise ValueError('WAV bytes/size/hash differ from provenance')
    if header.read_text()!=render(rows):raise ValueError('generated C table differs from verified WAV headers')
    return rows

def main():
    root=Path(__file__).resolve().parents[1]
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--cd',type=Path,default=root/'cd')
    p.add_argument('--header',type=Path,default=root/'port/wf_jo_music_headers.h')
    p.add_argument('--manifest',type=Path,default=root/'tools/music-headers.json');p.add_argument('--verify',action='store_true');a=p.parse_args()
    rows=(verify if a.verify else generate)(a.cd,a.header,a.manifest)
    print(json.dumps({'status':'VERIFIED' if a.verify else 'GENERATED','files':len(rows),'runtime_table_bytes':864,'header_sha256':hashlib.sha256(a.header.read_bytes()).hexdigest()}))
if __name__=='__main__':main()
