/* Mode 1 sets bit0 of object2+$1D ($1C12C9): right Demolition speaker.
 * Mode 2 sets bit0 of object0+$1D ($1C1275): left Demolition speaker.
 * The table cursor is a byte offset into $B14A and is advanced by 2 per event.
 */
const arcade_interstitial_scene_t arcade_interstitial_scenes[ARCADE_INTERSTITIAL_SCENES]={
 {1,1,2,2},
 {2,2,0,4},
};
const uint16_t arcade_interstitial_audio_commands[ARCADE_INTERSTITIAL_AUDIO_COMMANDS]={0x3179,0x316a,0x316b,0x3178};

void arcade_interstitial_player_begin(arcade_interstitial_player_t *p,unsigned scene_index){
 if(!p)return;
 *p=(arcade_interstitial_player_t){0};
 if(scene_index>=ARCADE_INTERSTITIAL_SCENES)return;
 p->active=true;p->audio_table_offset=arcade_interstitial_scenes[scene_index].initial_audio_table_offset;
}

uint16_t arcade_interstitial_player_step(arcade_interstitial_player_t *p,unsigned scene_index){
 if(!p||!p->active||scene_index>=ARCADE_INTERSTITIAL_SCENES)return 0;
 const arcade_interstitial_scene_t *scene=&arcade_interstitial_scenes[scene_index];
 const arcade_interstitial_object_t *obj=&arcade_interstitial_objects[scene->speaking_object];
 /* $B0C8: SUBI.w #1,+$22; BPL => no phase advance.  The native player
  * represents +$22's low byte because every recovered duration fits there. */
 if(p->phase && p->timer){--p->timer;if(p->timer)return 0;}
 if(p->phase>=obj->phase_count){p->active=false;return 0;}
 const arcade_interstitial_phase_t *ph=&obj->phases[p->phase++];
 p->frame=ph->frame;
 if(ph->duration==0xfe){p->active=false;p->timer=0;return 0;}
 /* After a phase is loaded, ROM stores duration in +$22. It takes duration+1
  * later calls before the next load; encode that as duration+1 countdown. */
 p->timer=(uint8_t)(ph->duration+1U);
 if(ph->audio_event){unsigned ix=p->audio_table_offset/2U;p->audio_table_offset=(uint8_t)(p->audio_table_offset+2U);return ix<ARCADE_INTERSTITIAL_AUDIO_COMMANDS?arcade_interstitial_audio_commands[ix]:0;}
 return 0;
}
